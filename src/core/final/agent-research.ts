/**
 * agent-research — 에이전트에게 "쓰기 전에 먼저 찾아보라"고 시킨다.
 *
 * ## 왜 필요한가
 * 에이전트(Codex·Claude Code)는 **스스로 웹을 검색할 수 있다.** 그런데 지시서에는
 * 검색하라는 말이 한 줄도 없었다. 주제만 던져주고 "써라"고 하니 모델이 이미 아는
 * 것만으로 쓴다 — 그게 "검색한 누구나 아는 내용만 나열한 느낌"의 원인이다.
 *
 * API 경로는 네이버·구글을 크롤링해 재료를 만들어 먹인다. 에이전트는 그 재료를
 * **직접, 더 최신으로** 구할 수 있다. 안 쓰면 손해다.
 *
 * ## 검색이 막혀 있어도 글은 나와야 한다
 * CLI 설정이나 망 사정으로 검색이 안 될 수 있다. 그때 작업이 실패하면 안 되므로
 * "가능하면" 이라고 적고, 못 찾았을 때 어떻게 할지도 함께 준다.
 */

export interface ResearchDirectiveInput {
  keyword: string;
  currentYear: number;
  contentMode?: string;
}

/** 모드마다 찾아야 할 것이 다르다 */
function targetsFor(contentMode: string | undefined, keyword: string, currentYear: number): string[] {
  const mode = String(contentMode || '').trim().toLowerCase();

  if (mode === 'shopping') {
    return [
      `"${keyword}" 의 **실제 판매 중인 제품**과 현재 사양 (모델명, 용량·크기 등 구매 결정에 쓰이는 스펙)`,
      '구매자들이 실제로 남긴 후기에서 **좋았던 점과 아쉬웠던 점** (별점 숫자가 아니라 문장)',
      '경쟁 제품과 갈리는 지점 — 어떤 사람에게 어느 쪽이 맞는지',
      '⚠️ 가격은 수시로 바뀝니다. 확인한 가격이라도 "확인 시점" 을 함께 적거나, 확실하지 않으면 쓰지 마세요.',
    ];
  }

  if (mode === 'adsense') {
    return [
      `"${keyword}" 에 대한 **1차 출처** (정부·공공기관·발표 원문). 블로그 요약본 말고 원문을 찾으세요.`,
      `${currentYear}년 기준으로 달라진 내용이 있는지`,
      '사람들이 실제로 헷갈려하는 지점과 그 정답',
    ];
  }

  if (mode === 'discover') {
    return [
      `"${keyword}" 에서 **최근에 실제로 벌어진 일** (언제, 무엇이, 왜 바뀌었는지)`,
      '그 변화가 보통 사람의 생활에 어떤 영향을 주는지',
      '⚠️ 디스커버는 시의성이 생명입니다. 낡은 정보로 쓰면 카드가 뜨지 않습니다.',
    ];
  }

  return [
    `"${keyword}" 로 검색한 사람들이 **실제로 묻는 질문** (지식인·커뮤니티·연관검색어)`,
    `${currentYear}년 현재의 조건·기준·절차 (지난 연도 자료를 그대로 쓰지 마세요)`,
    '1차 출처(공식 안내·공고·발표) — 블로그 요약본보다 원문을 우선합니다',
    '사람들이 실제로 막히는 지점 (반려 사유, 놓치기 쉬운 조건 등)',
  ];
}

/**
 * "먼저 찾아보고 쓰라"는 지시문. 검색 도구가 없으면 조용히 건너뛰고 쓰게 한다.
 */
export function buildResearchDirective(input: ResearchDirectiveInput): string {
  const { keyword, currentYear, contentMode } = input;
  const targets = targetsFor(contentMode, keyword, currentYear);

  return [
    '',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    '🔍 **[먼저 찾아보고, 그다음에 쓰세요]**',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    '',
    '**웹 검색 도구를 쓸 수 있으면 반드시 먼저 검색하세요.** 바로 쓰기 시작하지 마세요.',
    '알고 있는 것만으로 쓰면 어느 블로그에나 있는 글이 됩니다. 독자가 이 글을 읽을 이유가 없어집니다.',
    '',
    '**이번 글에서 찾아야 할 것:**',
    ...targets.map((t) => `  · ${t}`),
    '',
    '**찾은 뒤:**',
    '1. 확인한 사실만 본문에 씁니다. 검색으로 확인하지 못한 수치·날짜는 쓰지 않습니다.',
    '2. 출처가 서로 다르면 **더 권위 있는 쪽**(공식·기관)을 따르고, 갈린다는 사실 자체를 적어도 됩니다.',
    `3. ${currentYear}년 기준인지 확인하세요. 검색 결과에 지난 연도 자료가 섞여 옵니다.`,
    '4. metadata.json 의 `sources` 에 실제로 참고한 주소를 넣으세요 (배열, 없으면 빈 배열).',
    '',
    '**검색 도구를 쓸 수 없다면** 검색을 건너뛰고 글을 쓰되,',
    '확실하지 않은 수치·날짜·금액은 **아예 쓰지 마세요.** 지어내는 것보다 빼는 것이 낫습니다.',
    '',
  ].join('\n');
}
