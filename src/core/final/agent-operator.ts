/**
 * agent-operator — 에이전트를 "받아 적는 작성자"가 아니라 "판단하는 운영자"로 세운다.
 *
 * ## 사장님 요구
 * "에이전트모드로는 월 10억이상 수익을 내는 블로거 자체가 되서 내 툴에 있는 프롬프트와
 *  기능들을 분석해서 그에 맞게 글을 생성시킨다고 보면 되"
 *
 * ## 무엇이 실제로 효과가 있는가
 * 페르소나 문구("당신은 최고의 블로거입니다")만으로는 글이 크게 달라지지 않는다.
 * 실제 차이를 만드는 건 **순서를 강제하는 것**이다 —
 *   ① 규칙을 끝까지 읽고  ② 이 주제에 어떻게 적용할지 정하고  ③ 그다음에 쓴다.
 * 지금까지는 ①②를 건너뛰고 곧장 쓰게 했다. 에이전트는 ①②를 할 수 있는 도구인데
 * 그 능력을 안 쓰고 있었다 — 그러면 비싼 CLI 를 텍스트 생성기로만 쓰는 셈이다.
 *
 * ## 계획을 파일로 남기게 하는 이유
 * 머릿속으로만 계획하면 지키는지 알 수 없다. plan.md 로 적게 하면
 * (1) 모델이 스스로 점검하게 되고 (2) 결과가 이상할 때 어디서 어긋났는지 볼 수 있다.
 */

export interface OperatorBriefInput {
  keyword: string;
  /** 이 글이 노리는 모드 (사람이 읽는 이름). 모르는 모드면 undefined 가 들어온다 */
  modeLabel?: string | undefined;
}

/**
 * 지시서 맨 앞에 붙는 운영자 브리핑.
 * 규칙 뭉치보다 **먼저** 와야 한다 — 어떻게 읽을지를 먼저 정해줘야 읽는 방식이 달라진다.
 */
export function buildOperatorBrief(input: OperatorBriefInput): string {
  const { keyword, modeLabel } = input;

  return [
    '',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    '🎯 **[당신의 역할 — 작성자가 아니라 운영자입니다]**',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    '',
    '당신은 이 블로그를 실제로 굴려서 먹고사는 운영자입니다.',
    '글 한 편이 검색·피드에서 살아남는지가 수입으로 바로 이어집니다.',
    '그래서 **시키는 대로 채우는 것이 아니라, 이 주제에 무엇이 통할지 스스로 판단**해야 합니다.',
    '',
    '아래에 이 도구가 그동안 실측으로 쌓은 규칙들이 붙어 있습니다.',
    '각 규칙에는 **왜 그런지**가 함께 적혀 있습니다. 문구를 외우지 말고 이유를 읽으세요.',
    `그리고 "${keyword}"${modeLabel ? ` (${modeLabel})` : ''} 라는 이 주제에 그 이유가 어떻게 적용되는지 판단하세요.`,
    '',
    '**작업 순서를 지키세요. 곧장 본문부터 쓰지 마세요.**',
    '',
    '  1단계 · 읽기   — 아래 규칙을 끝까지 읽습니다.',
    '  2단계 · 찾기   — 웹 검색으로 이 주제의 최신 사실과 사람들의 실제 질문을 확보합니다.',
    '  3단계 · 계획   — `result/plan.md` 에 아래를 적습니다 (짧게, 10줄 이내):',
    '                    · 이 글을 읽을 사람은 어떤 상황에 있는가',
    '                    · 그 사람이 이미 아는 것 / 아직 모르는 것',
    '                    · 그래서 이 글이 무엇을 알려줘야 하는가 (다른 글과 갈리는 지점)',
    '                    · 소제목 계획과 각 소제목에서 줄 구체적 정보(수치·조건·절차)',
    '  4단계 · 쓰기   — 계획대로 `result/article.html` 을 씁니다.',
    '  5단계 · 검토   — 다 쓴 뒤 스스로 확인합니다:',
    '                    · 소제목마다 **그 글에만 있는 구체적 정보**가 들어갔는가',
    '                    · 검색으로 확인하지 않은 수치·날짜가 섞이지 않았는가',
    '                    · 누구나 쓸 수 있는 문장만 남은 문단은 없는가 (있으면 고쳐 쓰세요)',
    '',
    '⚠️ 3단계를 건너뛰면 5단계에서 걸립니다. 계획 없이 쓰면 "누구나 아는 내용" 이 나옵니다.',
    '',
  ].join('\n');
}

