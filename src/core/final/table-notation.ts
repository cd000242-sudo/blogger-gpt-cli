/**
 * table-notation — 표 안의 계산 표기를 기호로 통일한다. (v3.8.619)
 *
 * ## 사장님 실물 검수
 * "핵심 요약에 곱하기를 한글 그대로 적지 말고 X로 표기해야 되고"
 *
 * 실제 발행글 요약표: `봉급 계산 | 기존 봉급액 곱하기 1.039`
 *
 * 표는 문장이 아니라 **눈으로 훑는 자리**다. "곱하기"는 읽어야 알지만 `×` 는 보면 안다.
 * 좁은 칸에서 한 글자라도 줄어드는 쪽이 읽힌다.
 *
 * 모델에게 "기호로 써라"라고 시키는 대신 여기서 바꾼다 — 프롬프트 지시는 지켜질 때도
 * 있고 아닐 때도 있지만, 이 치환은 언제나 같은 결과를 낸다.
 *
 * 곱셈 기호는 알파벳 X 가 아니라 **곱셈표(U+00D7)** 를 쓴다. 글꼴에 따라 X 는
 * 변수처럼 보이고, 읽기 프로그램도 "엑스"로 읽는다.
 */

/** "곱하기" 를 곱셈 기호로 — 숫자·금액 사이에 있을 때만 바꾼다 */
const MULTIPLY_PHRASE = /\s*곱하기\s*/g;

/**
 * 표 셀의 계산 표기를 정리한다.
 * 셀이 아닌 본문 문장에는 쓰지 않는다 — 문장에서는 "곱합니다"가 자연스럽다.
 */
export function normalizeTableNotation(cell: string): string {
  return String(cell ?? '').replace(MULTIPLY_PHRASE, ' × ').replace(/\s{2,}/g, ' ').trim();
}
