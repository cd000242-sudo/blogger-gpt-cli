import { LEADERNAM_VOICE_RULES } from './voice-profile';

export type ToneKey = 'professional' | 'formal' | 'friendly' | 'conversational' | 'casual';

export function normalizeTone(toneStyle?: string | null): ToneKey {
  const t = String(toneStyle || '').toLowerCase().trim();
  return (['professional', 'formal', 'friendly', 'conversational', 'casual'] as const).includes(t as ToneKey) ? (t as ToneKey) : 'professional';
}

/** 어미 한 줄 — FAQ·요약·답변 상자·보강·자가 수정 프롬프트가 "본문과 같은 말투" 를 말할 때 쓴다 */
export function toneEndings(toneStyle?: string | null): string {
  switch (normalizeTone(toneStyle)) {
    case 'friendly': return '해요체("~해요", "~이에요")';
    case 'casual': return '해요체("~해요", "~이에요", "~구요", "~더라구요")';
    case 'conversational': return '합니다체("~합니다", "~입니다") 바탕에 공감 어미("~죠", "~거든요", "~잖아요")를 절마다 한두 번';
    case 'formal': return '격식체("~합니다", "~입니다", "~하시기 바랍니다")';
    // v3.8.721 — 전문적도 서술형 공감 어미를 절마다 한두 번 쓴다 (되묻는 "~죠?" 는 아니다)
    default: return '합니다체("~합니다", "~입니다") 바탕에 서술형 어미("~죠.", "~거든요.")를 절마다 한두 번';
  }
}

/** 본문 프롬프트의 금지 목록에 들어갈 "이 말투에서 하면 안 되는 것" 한 줄 */
export function toneForbidden(toneStyle?: string | null): string {
  switch (normalizeTone(toneStyle)) {
    case 'friendly':
    case 'casual': return '"~입니다", "~합니다" 딱딱한 말투 (→ "~해요", "~거든요"로)';
    case 'conversational': return '해요체로 통일하는 것 — 설명은 합니다체, 공감 어미("~죠", "~거든요")는 절마다 한두 번만';
    case 'formal': return '"~해요", "~거든요", "~죠" 구어체와 감탄·되묻기 — 격식체 안내문입니다';
    /**
     * v3.8.721 — 막을 것은 **되묻기**이지 서술형 어미가 아니다.
     * 예전엔 "~거든요" 자체를 반말투로 묶어 금지했는데, 그 탓에 글 전체가 "~합니다" 하나로만
     * 끝나 기계가 읽는 소리가 났다(실측: 긴 문단 61개 전부 합니다체).
     */
    default: return '"~해요" 해요체, 되묻기("~죠?", "어떠신가요?"), 감탄사 — 서술형 "~죠.", "~거든요." 는 절마다 한두 번 씁니다';
  }
}

/** 해요체로 기계 치환(발행 직전·절 본문)을 걸어도 되는 말투인가 — 대화체는 합니다체 바탕이라 걸면 안 된다 */
export function tonePrefersHaeyo(toneStyle?: string | null): boolean {
  const t = normalizeTone(toneStyle);
  return t === 'friendly' || t === 'casual';
}

/**
 * 🗣️ v3.8.721 — 발행 직전 **말투 섞기(voice-softener)** 를 걸어도 되는 말투인가.
 *
 * ## 왜 이 함수가 필요한가 (실제로 낸 사고)
 * v3.8.720 에서 후처리를 말투와 무관하게 돌렸다. 그런데 「전문적」 프롬프트는 그때
 * "~죠 를 쓰지 않습니다" 라고 **금지**하고 있었다. 프롬프트는 막고 후처리는 넣으니
 * 규칙이 둘로 갈려 싸웠고, 글은 34%만 섞인 채 들쭉날쭉해졌다 —
 * 사장님이 "전체적으로 말투가 하나가 되어야 돼" 라고 한 그 상태다.
 *
 * 이제 전문적·대화체는 프롬프트가 **먼저** 서술형 어미를 쓰게 하고, 후처리는 남은 자리를
 * 메우는 보조로만 돈다. 해요체(친근·캐주얼)와 격식체는 걸지 않는다 — 그쪽은 어미 체계가 다르다.
 */
export function toneAllowsVoiceSoftening(toneStyle?: string | null): boolean {
  const t = normalizeTone(toneStyle);
  return t === 'professional' || t === 'conversational';
}

/** 말투 섞임 검사(article-audit)에서 허용하는 소수 말투 비율 — 대화체는 섞는 것이 설계다 */
export function toneMixAllowance(toneStyle?: string | null): number {
  return normalizeTone(toneStyle) === 'conversational' ? 0.45 : 0.25;
}

