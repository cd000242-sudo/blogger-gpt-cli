/**
 * 🗣️ 겪은 사람의 목소리 (v3.8.470)
 *
 * 사용자 요구: "경험을 사용자가 적는것보다 … 키워드를 보고 추론해서 경험으로
 * 진짜 사람이 설명하듯이 글이 나오게 해야되" · "3인칭으로 나오면 안 되고".
 *
 * ## 무엇을 하는가
 * 지식인 **답변**에서 사람들이 실제로 막힌 지점을 뽑아, 본문이 그걸 아는 사람처럼
 * 쓰게 만든다. 인용하지 않는다 — "누가 그러던데" 없이 그냥 안다는 듯 쓴다.
 * 좋은 대필 작가가 하는 일과 같다: 실제 사례를 조사해 자기 목소리로 확신 있게 쓴다.
 *
 * ## 왜 답변인가 — 이미 긁고 있는데 버리고 있었다
 * content-crawler 가 `Q. 질문\nA. 답변` 을 통째로 수집하는데(naver-kin),
 * orchestration 은 `subheadings`(질문)만 꺼내 쓰고 **답변을 버렸다.**
 * 그 답변이 실제로 겪은 사람들이 쓴 내용이다 — "등본 때문에 반려됐다",
 * "2주라더니 한 달 걸렸다". 글에 사람 냄새를 낼 재료가 이미 손에 있었다.
 *
 * ## 무엇을 하지 않는가
 * 겪지 않은 일을 겪은 것처럼 쓰지 않는다. 구체적으로:
 *   · 날짜·기간·금액을 **1인칭 체험담으로** 지어내지 않는다
 *     ("제가 3월 8일에 신청해서 2주 만에 받았습니다")
 *   · 상품을 써본 척하지 않는다 (표시광고법상 허위 후기다)
 * 대신 **어디서 막히는지 아는 말투**로 쓴다. 신뢰는 날짜를 대는 데서 오지 않고
 * "이 사람 아는구나" 에서 온다.
 *
 * 비용: LLM 호출 0. 이미 수집한 텍스트에서 뽑아 프롬프트 블록만 만든다.
 */

export interface LivedSignal {
  /** 사람들이 실제로 막힌 지점 한 줄 */
  text: string;
  /** 어떤 종류인지 — 프롬프트에서 다르게 쓰인다 */
  kind: 'friction' | 'duration' | 'cost' | 'condition' | 'tip';
}

/** 답변에서 걷어낼 잡소리 */
const NOISE = /(도움이\s*되셨|채택\s*부탁|답변\s*드립니다|안녕하세요|감사합니다|추천\s*드려요|문의\s*주세요|상담\s*환영|010[-\s]?\d{3,4})/;

/** 이 말이 들어 있으면 "실제로 겪은 이야기" 일 확률이 높다 */
const KIND_PATTERNS: Array<[LivedSignal['kind'], RegExp]> = [
  ['friction', /반려|거절|안\s*되|막히|실패|누락|빠뜨|재신청|보완|다시\s*(가|해|제출)|헛걸음|퇴짜/],
  ['duration', /(\d+\s*(일|주|개월|달|시간|분))\s*(걸|소요|정도|이상|만에|뒤|후)/],
  ['cost', /(\d[\d,]*\s*(원|만원|천원))/],
  ['condition', /(경우|면\s|이라면|일\s*때|해당|기준|조건|자격)/],
  ['tip', /(먼저|미리|반드시|꼭|주의|참고로|팁|추천)/],
];

const clean = (v: unknown): string =>
  String(v ?? '').replace(/<\/?[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();

/** 한 문장이 쓸 만한 신호인지 */
function classify(sentence: string): LivedSignal['kind'] | null {
  if (sentence.length < 12 || sentence.length > 120) return null;
  if (NOISE.test(sentence)) return null;
  // 링크·아이디·해시태그가 섞인 줄은 광고일 확률이 높다
  if (/https?:\/\/|@[\w.]+|#\w+/.test(sentence)) return null;
  for (const [kind, re] of KIND_PATTERNS) {
    if (re.test(sentence)) return kind;
  }
  return null;
}

/** 한 덩어리 텍스트에서 신호 문장을 뽑아 out 에 담는다 */
function harvest(text: string, out: LivedSignal[], seen: Set<string>, limit: number): void {
  for (const raw of text.split(/(?<=[.!?。])\s+|\n+/)) {
    if (out.length >= limit) return;
    const sentence = raw.trim().replace(/^[·\-*\d.)\s]+/, '');
    const kind = classify(sentence);
    if (!kind) continue;

    const key = sentence.replace(/\s/g, '').slice(0, 24);
    if (seen.has(key)) continue;
    seen.add(key);
    out.push({ text: sentence, kind });
  }
}

/**
 * 수집한 자료에서 "실제로 겪은 지점"을 뽑는다.
 *
 * 🧩 v3.8.470 — **모드마다 재료가 다르므로 창구를 둘로 연다.**
 *   사용자 요구: "이게 어떤 모드든 이런 식으로 나와야 되".
 *     · 정보성·SEO·애드센스·페러프레이징 → 지식인 **답변**
 *     · 쇼핑 → **상품 후기** (구매자가 직접 쓴 것이라 지식인만큼 진짜다)
 *   둘 다 실제 사용자가 쓴 글이라 "겪은 사람의 말투" 재료로 같은 값을 한다.
 *
 * @param posts   crawledPosts — source 가 naver-kin 인 것의 content 에 `A.` 답변이 있다
 * @param reviews 상품 후기 — 쇼핑 모드에서 이미 수집해 둔 것
 */
export function extractLivedSignals(
  posts: Array<{ source?: string; content?: string }> | undefined,
  reviews?: Array<{ body?: string }> | undefined,
  limit = 12,
): LivedSignal[] {
  const out: LivedSignal[] = [];
  const seen = new Set<string>();

  // ① 상품 후기 먼저 — 쇼핑 글에서는 이게 가장 생생하다
  for (const r of reviews || []) {
    if (out.length >= limit) break;
    const body = clean(r?.body);
    if (body) harvest(body, out, seen, limit);
  }

  // ② 지식인 답변
  for (const post of posts || []) {
    if (out.length >= limit) break;
    if (String(post?.source || '') !== 'naver-kin') continue;
    const body = clean(post?.content);
    if (!body) continue;

    // `Q. 질문 A. 답변` 에서 답변 쪽만 본다 — 질문은 이미 제목 재료로 쓰고 있다
    const answerPart = body.includes('A.') ? body.slice(body.indexOf('A.') + 2) : body;
    harvest(answerPart, out, seen, limit);
  }
  return out;
}

/**
 * 뽑은 신호를 **인용이 아니라 아는 사람의 말투**로 쓰게 하는 프롬프트 블록.
 *
 * 신호가 없으면 빈 문자열 — 프롬프트가 이전과 완전히 같아진다.
 */
export function buildLivedVoiceBlock(signals: LivedSignal[]): string {
  if (!signals || signals.length === 0) return '';

  const byKind = (k: LivedSignal['kind']) => signals.filter((s) => s.kind === k).map((s) => s.text);
  const section = (label: string, items: string[]) =>
    (items.length ? `${label}\n${items.map((t) => `  · ${t}`).join('\n')}\n` : '');

  return `

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
🗣️ **[이 주제에서 사람들이 실제로 막힌 지점]**
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
아래는 이 주제를 실제로 겪은 사람들이 남긴 내용에서 뽑은 것입니다.

${section('막히는 지점:', byKind('friction'))}${section('걸리는 시간:', byKind('duration'))}${section('드는 돈:', byKind('cost'))}${section('갈리는 조건:', byKind('condition'))}${section('미리 알면 좋은 것:', byKind('tip'))}
**이 재료를 이렇게 쓰세요:**

1. **인용하지 마세요.** "누가 그러던데", "후기를 보면", "많은 분들이" — 전부 쓰지 마세요.
   조사한 티를 내지 말고, 원래 알고 있던 것처럼 그냥 단정해서 쓰세요.
     (X) 후기를 보면 등본 때문에 반려되는 경우가 많다고 합니다
     (O) 등본 유효기간부터 확인하세요. 여기서 반려되는 경우가 제일 많습니다

2. **"제가 ~해봤는데" 는 쓰지 마세요.** 겪지 않은 일을 겪은 것처럼 쓰면 안 됩니다.
   대신 **어디서 막히는지 아는 사람의 말투**로 쓰세요. 그게 더 믿음직합니다.
     (X) 제가 3월에 신청해서 2주 만에 받았습니다
     (O) 서류만 갖춰지면 오래 안 걸립니다. 문제는 대개 서류에서 생깁니다

3. **순서와 우선순위를 매기세요.** 이게 사람 글과 기계 글을 가르는 가장 큰 차이입니다.
   "1) 2) 3)" 나열이 아니라 "이것부터 하세요, 이건 나중에 해도 됩니다" 로.

4. **조건을 나누세요.** "~한 분이라면" / "~인 경우에는 오히려" 처럼
   읽는 사람의 상황에 따라 답이 갈리는 지점을 짚어 주세요.

5. **모르는 건 모른다고 하세요.** "정확한 금액은 신청 시점 기준으로 달라집니다" 같은
   솔직한 한계 표시가 오히려 신뢰를 만듭니다. 다 아는 척하면 광고글처럼 읽힙니다.

6. 위 목록에 **없는** 수치·기간·금액을 새로 지어내지 마세요.
`;
}

