/**
 * 중복 회피 블록을 만든다.
 *
 * 배경 — 2026-07-28 실측: 본문 유사도 0.35 이상이 4개 클러스터 11편.
 *   그중 3개는 지역 시리즈(정당한 분화)였고 실질 중복은 청년내일저축계좌 4편뿐이다.
 *   즉 지금 규모는 크지 않지만, 하루 5~10편을 같은 주제군에서 뽑으면 반드시 커진다.
 *
 * ⚠️ 차단하지 않는다. 사용자 원칙: "검수 때문에 발행이 안 되면 절대 안 된다."
 *   대신 이미 있는 글의 제목을 모델에게 보여주고 **각도를 다르게 잡게** 한다.
 *   추가 LLM 호출이 없으므로 비용도 늘지 않는다.
 */
export function buildUniquenessBlock(existingTitles: string[]): string {
  const titles = (Array.isArray(existingTitles) ? existingTitles : [])
    .map(t => String(t || '').trim())
    .filter(Boolean)
    .slice(0, 8);
  if (titles.length === 0) return '';

  return `

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
🧬 **[중복 회피 — 이 사이트에 이미 있는 글]**
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

같은 사이트에 아래 글들이 이미 있습니다:
${titles.map(t => `   · ${t}`).join('\n')}

**이 글은 위와 겹치면 안 됩니다.** 검색엔진이 같은 사이트의 비슷한 글을 발견하면
둘 다 순위를 잃습니다(자기잠식). 다음을 지키세요:

1. **각도를 다르게 잡으세요.** 위 글이 "신청 방법"이면 이 글은 "지급일·심사기간"이나
   "거절 사유와 대응"처럼 독자가 다음에 궁금해할 지점을 다루세요.
2. **위 글의 내용을 요약해 반복하지 마세요.** 필요하면 한 문장으로 언급하고 넘어가세요.
3. **제목이 위와 수식어만 다르면 안 됩니다.** "완벽 가이드" / "총정리" / "한눈에" 같은
   장식어만 바꾼 제목은 같은 글로 취급됩니다.
4. 이 글에서만 얻을 수 있는 정보가 최소 3가지 있어야 합니다.
`;
}

/** 실속 규칙이 프롬프트에 들어갔는지 판정 (테스트·가드용) */
export function hasSubstanceRules(prompt: string): boolean {
  return typeof prompt === 'string' && prompt.includes('[실속 강제 —');
}

/** 최신성 규칙이 들어갔는지 */
export function hasFreshnessRules(prompt: string): boolean {
  return typeof prompt === 'string' && prompt.includes('[최신성 —');
}
