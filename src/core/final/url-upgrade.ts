/**
 * url-upgrade — URL 을 넣었으면 그 글의 **상위호환**을 쓴다. (v3.8.596)
 *
 * ## 사장님 지적
 * "url을 넣으면 그 블로그를 적는 게 아니라 그 블로그에서 적은 글을 파악하고 확인해서
 *  그 글보다 더 상위호환으로 작성해야지"
 *
 * ## 프롬프트가 정반대를 시키고 있었다
 * URL 모드의 세 프롬프트가 한결같이 이렇게 말했다:
 *   · "원본 제목과 **완전히 다른** 새로운 제목 생성"
 *   · "참고 소제목과 **완전히 다른** 새로운 소제목 5개"
 *   · "**새 관점**과 새 문장으로 재작성"
 * 목표가 **다름**이었지 **나음**이 아니었다. 다르라고 시키면 모델은 주제에서 멀어진다 —
 * 검색한 사람은 그 주제를 찾은 것이지 '새 관점'을 찾은 게 아닌데도.
 *
 * 여기에 수집 실패(제목이 블로그 별명)까지 겹치자 글 전체가
 * "그 사람 블로그를 어떻게 읽을 것인가"가 됐다(발행 사고).
 *
 * ## 무엇을 바꾸나
 * 기준을 **같은 검색 의도, 더 나은 답**으로 바꾼다.
 *   ① 원문이 무엇에 답하는 글인지 먼저 파악한다.
 *   ② 원문이 다룬 것은 **빠짐없이** 다루되 더 구체적으로 쓴다.
 *   ③ 원문이 빠뜨린 것을 채운다 — 그게 상위호환의 실체다.
 *   ④ 원문·블로그·글쓴이를 **글의 소재로 삼지 않는다.**
 *   ⑤ 문장은 복사하지 않는다 (중복 문서).
 *
 * ②③ 과 ⑤ 는 부딪히지 않는다 — 같은 것을 다루되 우리 문장으로 더 깊게 쓰는 것이다.
 */

export interface UpgradeSource {
  title: string;
  content: string;
  subheadings: string[];
  url: string;
  metaDescription?: string;
}

/** 원문에서 프롬프트에 실을 만큼만 잘라 온다 */
export function buildUpgradeBrief(source: UpgradeSource, contentChars = 6000): string {
  const lines: string[] = [
    '[원문 — 우리가 이겨야 할 글]',
    `제목: ${String(source.title || '').trim() || '(없음)'}`,
  ];
  const subs = (source.subheadings || []).filter(Boolean).slice(0, 15);
  if (subs.length) {
    lines.push('원문이 다룬 항목:', ...subs.map((s) => `  · ${s}`));
  }
  const body = String(source.content || '').replace(/\s+/g, ' ').trim();
  if (body) lines.push('원문 본문:', body.slice(0, contentChars));
  return lines.join('\n');
}

